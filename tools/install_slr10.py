"""Apply only SLR_10 changes; preserve .env, migrations, media and SLR_11 work."""
import argparse
from datetime import datetime
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys

SOURCE = Path(__file__).resolve().parents[1]
PILLOW_PIN = 'Pillow==13.0.0'
IGNORES = '\n# SLR_10 local files\n.slr10-backups/\ncode/frontend/node_modules/\ncode/frontend/dist/\ncode/backend/private_backups/\n'
URL_BLOCK = "\n# SLR_10 input endpoints\nfrom django.urls import include\nurlpatterns += [path('api/v1/', include('reporting.urls'))]\n"
APP_BLOCK = "\n# SLR_10 input service\nif 'reporting' not in INSTALLED_APPS:\n    INSTALLED_APPS += ['reporting']\n"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pillow_lines(text):
    return [line.split('#', 1)[0].strip() for line in text.splitlines()
            if re.match(r'^pillow\s*(?:[<=>!~]|$)', line.strip(), re.I)]


def install(target, dry_run=False):
    target = target.resolve()
    if target == SOURCE:
        raise ValueError('Pilih repository Silar yang sudah ada, bukan folder paket hasil ekstraksi.')
    if not (target / 'code/backend/manage.py').is_file():
        raise ValueError('Folder tujuan harus akar repository Silar yang memuat code/backend/manage.py.')
    manifest = json.loads((SOURCE / 'tools/release-manifest.json').read_text())
    plan = []
    conflicts = []
    for name, record in manifest['files'].items():
        if name in ('code/backend/config/urls.py', 'code/backend/config/settings.py', 'code/backend/requirements.txt', '.gitignore'):
            continue
        source = SOURCE / name
        dest = target / name
        if not source.resolve().is_relative_to(SOURCE) or not dest.resolve().is_relative_to(target):
            raise ValueError('Path paket tidak sah.')
        if sha(source) != record['sha256']:
            raise ValueError('Integritas paket berubah: ' + name)
        if dest.exists():
            digest = sha(dest)
            if digest == record['sha256'] or digest in record.get('equivalent_sha256', []):
                continue
            accepted = set(record.get('accepted_previous_sha256', []))
            accepted.add(record.get('baseline_sha256'))
            if digest not in accepted:
                conflicts.append(name)
                continue
        plan.append((name, source.read_bytes()))
    for name, token, block in [
        ('code/backend/config/urls.py', "include('reporting.urls')", URL_BLOCK),
        ('code/backend/config/settings.py', "'reporting'", APP_BLOCK),
    ]:
        path = target / name
        text = path.read_text()
        if token not in text and token.replace("'", '"') not in text:
            plan.append((name, (text.rstrip() + '\n' + block).encode()))
    requirements = target / 'code/backend/requirements.txt'
    existing_requirements = requirements.read_text()
    pillow = pillow_lines(existing_requirements)
    if pillow and [x.lower() for x in pillow] not in (['pillow==12.3.0'], [PILLOW_PIN.lower()]):
        conflicts.append('code/backend/requirements.txt (versi Pillow lokal berbeda)')
    elif pillow and pillow[0].lower() == 'pillow==12.3.0':
        updated = re.sub(r'(?im)^(\s*pillow\s*==\s*)12\.3\.0(?=\s*(?:#|$))', r'\g<1>13.0.0', existing_requirements)
        plan.append(('code/backend/requirements.txt', updated.encode()))
    elif not pillow:
        plan.append(('code/backend/requirements.txt', (existing_requirements.rstrip() + '\n' + PILLOW_PIN + '\n').encode()))
    # Keep SLR_11's dependency file intact, and reject a different local baseline
    # before copying any SLR_10 files. Setup resolves both files together.
    ai_requirements = target / 'code/backend/requirements-ai.txt'
    if ai_requirements.exists():
        ai_pillow = pillow_lines(ai_requirements.read_text())
        if any(pin.lower() != PILLOW_PIN.lower() for pin in ai_pillow):
            conflicts.append('code/backend/requirements-ai.txt (baseline Pillow belum 13.0.0)')
    ignore_path = target / '.gitignore'
    existing = ignore_path.read_text() if ignore_path.exists() else ''
    if '.slr10-backups/' not in existing:
        plan.append(('.gitignore', (existing.rstrip() + '\n' + IGNORES).encode()))
    # The manifest does not hash itself. Only known prior manifests may be
    # replaced, using a separate digest list generated by the release builder.
    manifest_name = 'tools/release-manifest.json'
    installed_manifest = target / manifest_name
    source_manifest = SOURCE / manifest_name
    if not installed_manifest.exists():
        plan.append((manifest_name, source_manifest.read_bytes()))
    elif installed_manifest.read_bytes().replace(b'\r\n', b'\n') != source_manifest.read_bytes().replace(b'\r\n', b'\n'):
        if sha(installed_manifest) in manifest.get('previous_manifest_sha256', []):
            plan.append((manifest_name, source_manifest.read_bytes()))
        else:
            conflicts.append(manifest_name)
    if conflicts:
        raise ValueError('Ada berkas lokal yang berbeda. Tidak ada berkas yang disalin. Tinjau: ' + ', '.join(conflicts))
    print('Paket SLR_10:', manifest['version'])
    print('Berkas baru/perubahan yang akan diterapkan:', len(plan))
    if dry_run:
        for name, _ in plan:
            print(name)
        return len(plan)
    backup = target / '.slr10-backups' / datetime.now().strftime('%Y%m%d-%H%M%S-%f')
    # Ignore the backup before writing any old project files into it.
    for name, data in sorted(plan, key=lambda item: item[0] != '.gitignore'):
        dest = target / name
        if dest.exists():
            old = backup / name
            old.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(dest, old)
        dest.parent.mkdir(parents=True, exist_ok=True)
        temporary = dest.with_name(dest.name + '.slr10-tmp')
        temporary.write_bytes(data)
        temporary.replace(dest)
    print('Pemasangan kode selesai. .env, database, migration lama, dan aset model tidak diganti.')
    print('Selanjutnya jalankan SIAPKAN_SLR10.bat dari repository tujuan.')
    return len(plan)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--target')
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args()
    value = args.target or input('Tempel path folder utama repository Silar: ').strip().strip('"')
    try:
        install(Path(value), args.dry_run)
    except (ValueError, OSError) as error:
        print('Pemasangan belum dilakukan/selesai:', str(error))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
